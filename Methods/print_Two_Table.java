package Methods;

public class print_Two_Table {

  static  void printTwoTable() {
        for (int i = 1; i <= 10; i++) {
            int ans = 2 * i;
            System.out.println("2 x " + i + " = " + ans);
        }
      
    }

    public static void main(String[] args) {
        printTwoTable();
    }

}
